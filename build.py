"""Generate the data files from values.py, compile the jar, stage the release folder and zip it.

Run from anywhere: python build.py
Needs javac/jar (JDK 17+) on PATH and the game plus LunaLib under D:/Games/StarSector0985.

Writes, from values.py:
- data/config/settings.json             Lite defaults (used with or without LunaLib)
- data/config/LunaSettings.csv          one LunaLib field per value
- data/config/survival_mode_lite_fields.json   field id -> setting key, list index, unit, on/off switch and
  vanilla value (read by the plugin)
- the tables in README.md between the TABLES markers
- forum-post.txt from forum-post.template.txt (the full value tables and the setting count)
Then jars/SurvivalModeLite.jar, the staging folder SurvivalModeLite/ and SurvivalModeLite.zip.

Checks:
- every key exists in the base game settings.json (a typo would silently do nothing), lists match its length
- no UTF-8 BOM, no forbidden Java APIs (the game refuses java.io, java.nio.file, java.lang.reflect)
- versions agree between mod_info.json, the .version file and the ZIP
"""
import csv
import glob
import io
import json
import os
import re
import shutil
import subprocess
import zipfile

from values import ROWS, TABS, FIXED_RULES, GROUPS, OFF, NEW_GAME

ROOT = os.path.dirname(os.path.abspath(__file__))
GAME = "D:/Games/StarSector0985"
GAME_SETTINGS = GAME + "/starsector-core/data/config/settings.json"
CORE_JARS = ["starfarer.api.jar", "json.jar", "log4j-1.2.9.jar"]
LIB_GLOBS = ["LunaLib*/jars/LunaLib.jar"]
STAGE_NAME = "SurvivalModeLite"
STAGE = os.path.join(ROOT, STAGE_NAME)
ZIP = os.path.join(ROOT, STAGE_NAME + ".zip")
JAR = os.path.join(ROOT, "jars", STAGE_NAME + ".jar")
VERSION_FILE = "survival_mode_lite.version"
SHIP = ["mod_info.json", VERSION_FILE, "icon.png", "data", "jars", "graphics"]
MOD_ID = "survival_mode_lite"


# ---------------------------------------------------------------- formatting

def num(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return s if s != "-0" else "0"


def show(unit, v):
    """How a value reads in the README and the LunaLib descriptions."""
    if isinstance(v, str):
        return v
    if unit == "bool":
        return "yes" if v else "no"
    if unit == "x":
        return "x" + num(v)
    if unit == "pct":
        return num(v * 100) + "%"
    if unit == "int":
        return "{:,}".format(int(v))
    if unit == "per100":
        return num(v * 100)
    return num(v)


def luna(text):
    """LunaLib draws names and descriptions through String.format (TooltipMakerAPI.addPara with highlights),
    so a bare % crashes the game when the tab opens. Write the word instead."""
    return re.sub(r"\s*%", " percent", text)


def field_id(key, index):
    return "sml_" + key[len("ext_"):] + ("" if index is None else "_%d" % index)


def group(key, label):
    """(switch field id, switch label) for a key that is not a yes/no rule."""
    gid, glabel = GROUPS.get(key, (key[len("ext_"):], label))
    return "sml_on_" + gid, glabel


def off_value(key, van):
    """What the game gets when the key's switch is off: a number, or the name of a base game setting."""
    if key in OFF:
        return OFF[key]
    if isinstance(van, (int, float)) and not isinstance(van, bool):
        return van
    raise SystemExit("No vanilla value for " + key + ": add it to OFF in values.py")


# ---------------------------------------------------------------- generation

def gen_settings_json():
    lines = ["{",
             "\t# Survival Mode - Lite: generated by build.py from values.py. Edit values.py, not this file.",
             "\t# Only matters in a campaign started in Survival mode. With LunaLib these are only the defaults.",
             "\t# The comment after each value is: survival / vanilla.",
             "\t# Lists start with \"core_clearArray\" so they replace the survival list instead of adding to it.",
             ""]
    lists = {}
    for tab, label, key, index, unit, surv, lite, van, note in ROWS:
        if index is not None:
            lists.setdefault(key, {})[index] = (label, surv, lite, van, unit)
            continue
        if unit == "bool" or lite == surv:
            continue
        lines.append('\t"%s":%s,\t# %s: %s / %s' % (key, num(lite), label, show(unit, surv), show(unit, van)))
    for key, entries in lists.items():
        idx = sorted(entries)
        lite = [num(entries[i][2]) for i in idx]
        surv = [num(entries[i][1]) for i in idx]
        lines.append('\t"%s":["core_clearArray", %s],\t# survival [%s]' % (key, ", ".join(lite), ", ".join(surv)))
    lines.append("}")
    write(os.path.join("data", "config", "settings.json"), "\n".join(lines) + "\n")


def limits(unit, key, surv, van):
    vnum = van if isinstance(van, (int, float)) and not isinstance(van, bool) else 0
    if unit == "per100":
        return 0, 20
    if unit == "pct":
        lo = -100 if surv < 0 else 0
        hi = max(100, surv * 200, vnum * 200)
    elif unit == "x":
        lo, hi = 0, max(10, surv * 2.5, vnum * 2.5)
    elif unit == "num":
        lo, hi = 0, max(1, surv * 3, vnum * 3)
    else:
        lo, hi = 0, max(10, surv * 4, vnum * 4)
    overrides = {
        "ext_corruptionExponent": (1, 5),
        "ext_corruptionThreshold": (0, 5000000),
        "ext_retirementMinCycles": (0, 200),
        "ext_retirementMaxCycles": (0, 200),
    }
    return overrides.get(key, (lo, hi))


def gen_luna():
    out = io.StringIO()
    w = csv.writer(out, lineterminator="\n")
    w.writerow(["fieldID", "fieldName", "fieldType", "defaultValue", "secondaryValue", "fieldDescription",
                "minValue", "maxValue", "tab"])
    fields = []
    switches = set()
    for t, (tab, header) in enumerate(TABS):
        tid = re.sub(r"[^a-z]+", "_", tab.lower()).strip("_")
        if t == 0:
            w.writerow(["sml_intro", "Intro", "Text",
                        "Every value starts at Lite, halfway between vanilla and survival. Each description gives the "
                        "survival and the vanilla value. Every change has an on/off switch above its numbers: off "
                        "uses the vanilla value. Only campaigns started in Survival mode use these. "
                        "Changes apply at once, unless the description says otherwise.", "", "", "", "", tab])
        w.writerow(["sml_header_" + tid, header + " Header", "Header", header, "", "", "", "", tab])
        for row_tab, label, key, index, unit, surv, lite, van, note in ROWS:
            if row_tab != tab:
                continue
            switch = None
            if unit != "bool":
                switch, glabel = group(key, label)
                if switch not in switches:
                    if any(group(r[2], r[1])[0] == switch and r[0] != tab for r in ROWS):
                        raise SystemExit("Switch %s spans two tabs" % switch)
                    switches.add(switch)
                    rows = [r for r in ROWS if r[4] != "bool" and group(r[2], r[1])[0] == switch]
                    sdesc = ("On: the survival change, using the number%s below. Off: vanilla (%s)."
                             % ("s" if len(rows) > 1 else "", show(unit, van)))
                    if any(r[8] == NEW_GAME for r in rows):
                        sdesc += " " + NEW_GAME
                    w.writerow([switch, luna("Survival change: " + glabel), "Boolean", "true", "", luna(sdesc), "", "",
                                tab])
            fid = field_id(key, index)
            desc = "Survival: %s. Vanilla: %s." % (show(unit, surv), show(unit, van))
            if note:
                desc += " " + note
            if unit == "bool":
                w.writerow([fid, luna(label), "Boolean", "true" if lite else "false", "", luna(desc), "", "", tab])
            else:
                lo, hi = limits(unit, key, surv, van)
                default = lite * 100 if unit in ("pct", "per100") else lite
                ftype = "Int" if unit == "int" else "Double"
                if ftype == "Double" and abs(round(default, 2) - default) > 1e-9:
                    raise SystemExit("%s default %s has more than 2 decimals; LunaLib's slider rounds it" % (fid, default))
                w.writerow([fid, luna(label), ftype, num(default) if ftype == "Double" else int(default), "",
                            luna(desc), num(lo), num(hi), tab])
            entry = {"id": fid, "key": key, "unit": unit}
            if index is not None:
                entry["index"] = index
            if switch is not None:
                entry["switch"] = switch
                off = off_value(key, van)
                entry["offKey" if isinstance(off, str) else "off"] = off
            fields.append(entry)
    if "%" in out.getvalue():
        raise SystemExit("LunaSettings.csv has a % sign; LunaLib's String.format would crash the game")
    write(os.path.join("data", "config", "LunaSettings.csv"), out.getvalue())
    write(os.path.join("data", "config", "survival_mode_lite_fields.json"),
          json.dumps({"fields": fields}, indent=1) + "\n")
    return len(fields), len(switches)


def gen_readme():
    parts = []
    for tab, header in TABS:
        parts.append("### " + header + "\n")
        parts.append("| Thing changed from base game | Survival | Lite | Vanilla |")
        parts.append("| --- | --- | --- | --- |")
        for row_tab, label, key, index, unit, surv, lite, van, note in ROWS:
            if row_tab == tab:
                parts.append("| %s | %s | %s | %s |" % (label, show(unit, surv), show(unit, lite), show(unit, van)))
        parts.append("")
    parts.append("### Survival rules that are not settings (not customizable)\n")
    parts.append("| Thing changed from base game | Survival | Lite | Vanilla |")
    parts.append("| --- | --- | --- | --- |")
    for label, surv, van in FIXED_RULES:
        parts.append("| %s | %s | same as survival | %s |" % (label, surv, van))
    parts.append("")
    path = os.path.join(ROOT, "README.md")
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    start, end = "<!-- TABLES START -->", "<!-- TABLES END -->"
    if start not in text or end not in text:
        raise SystemExit("README.md lacks the TABLES markers")
    text = text[:text.index(start) + len(start)] + "\n\n" + "\n".join(parts) + "\n" + text[text.index(end):]
    write("README.md", text)


def gen_forum_post(field_count, switch_count):
    parts = []
    for tab, header in TABS:
        parts.append("[b]%s[/b]" % header)
        parts.append("[table]")
        parts.append("[tr][td][b]What[/b][/td][td][b]Survival[/b][/td][td][b]Lite[/b][/td][td][b]Vanilla[/b][/td][/tr]")
        for row_tab, label, key, index, unit, surv, lite, van, note in ROWS:
            if row_tab == tab:
                parts.append("[tr][td]%s[/td][td]%s[/td][td]%s[/td][td]%s[/td][/tr]"
                             % (label, show(unit, surv), show(unit, lite), show(unit, van)))
        parts.append("[/table]")
        parts.append("")
    with open(os.path.join(ROOT, "forum-post.template.txt"), encoding="utf-8") as fh:
        text = fh.read()
    text = text.replace("{{VALUE_TABLES}}", "\n".join(parts).rstrip())
    text = text.replace("{{FIELD_COUNT}}", str(field_count))
    text = text.replace("{{SWITCH_COUNT}}", str(switch_count))
    if any(ord(c) > 127 for c in text):
        raise SystemExit("forum-post.txt must be plain ASCII (the forum rejects other characters)")
    write("forum-post.txt", text)


def write(rel, text):
    with open(os.path.join(ROOT, rel), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


# ---------------------------------------------------------------- checks

def strip_comments(text):
    """Drop # comments outside double quotes, the way the game does."""
    out = []
    for line in text.splitlines():
        quoted = False
        for i, ch in enumerate(line):
            if ch == '"':
                quoted = not quoted
            elif ch == "#" and not quoted:
                line = line[:i]
                break
        out.append(line)
    return re.sub(r",(\s*[}\]])", r"\1", "\n".join(out))


def base_settings():
    """key -> list length (or None for a plain value) for the base game's top-level ext_ keys."""
    with open(GAME_SETTINGS, encoding="utf-8") as fh:
        text = strip_comments(fh.read())
    found = {}
    for m in re.finditer(r'^\s*"(ext_[A-Za-z_]+)"\s*:\s*(\[[^\]]*\]|[^,\n]+)', text, re.M):
        value = m.group(2).strip()
        found[m.group(1)] = len(value[1:-1].split(",")) if value.startswith("[") else None
    return found


def check():
    base = base_settings()
    seen = set()
    for tab, label, key, index, unit, surv, lite, van, note in ROWS:
        if key not in base:
            raise SystemExit("Not a game setting: " + key)
        if (base[key] is not None) != (index is not None):
            raise SystemExit("List vs value mismatch: " + key)
        if index is not None and index >= base[key]:
            raise SystemExit("Index past the end of the game's list: %s[%d]" % (key, index))
        fid = field_id(key, index)
        if fid in seen:
            raise SystemExit("Same field twice: " + fid)
        seen.add(fid)
    with open(os.path.join(ROOT, "data", "config", "settings.json"), encoding="utf-8") as fh:
        ours = json.loads(strip_comments(fh.read()))
    for key, value in ours.items():
        if isinstance(value, list) and (value[0] != "core_clearArray" or len(value) - 1 != base[key]):
            raise SystemExit("Bad list: " + key)
    with open(GAME_SETTINGS, encoding="utf-8") as fh:
        game_text = strip_comments(fh.read())
    for key, off in OFF.items():
        if key not in base:
            raise SystemExit("OFF names an unknown setting: " + key)
        if isinstance(off, str) and not re.search(r'^\s*"%s"\s*:\s*[-0-9.]' % re.escape(off), game_text, re.M):
            raise SystemExit("OFF copies %s, which is not a plain number in the game's settings" % off)
    for key in GROUPS:
        if key not in base:
            raise SystemExit("GROUPS names an unknown setting: " + key)
    print(len(ROWS), "values checked against", GAME_SETTINGS)

    with open(os.path.join(ROOT, "mod_info.json"), encoding="utf-8") as fh:
        info = json.load(fh)
    with open(os.path.join(ROOT, VERSION_FILE), encoding="utf-8") as fh:
        ver = json.load(fh)["modVersion"]
    file_version = "%d.%d.%d" % (ver["major"], ver["minor"], ver["patch"])
    if info["version"] != file_version:
        raise SystemExit("mod_info %s vs version file %s" % (info["version"], file_version))
    return info["version"]


# ---------------------------------------------------------------- build

def classpath():
    jars = [GAME + "/starsector-core/" + j for j in CORE_JARS]
    for pattern in LIB_GLOBS:
        found = sorted(glob.glob(GAME + "/mods/" + pattern))
        if not found:
            raise SystemExit("Missing library: " + pattern)
        jars += found
    return os.pathsep.join(jars)


def compile_jar():
    out = os.path.join(ROOT, "build", "classes")
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)
    sources = glob.glob(os.path.join(ROOT, "src", "**", "*.java"), recursive=True)
    result = subprocess.run(["javac", "--release", "17", "-nowarn", "-encoding", "UTF-8", "-d", out,
                             "-sourcepath", os.path.join(ROOT, "src"), "-cp", classpath()] + sources)
    if result.returncode != 0:
        raise SystemExit("javac failed")
    for path in glob.glob(os.path.join(out, "**", "*.class"), recursive=True):
        with open(path, "rb") as fh:
            data = fh.read()
        for needle in (b"java/io/", b"java/nio/file/", b"java/lang/reflect/"):
            if needle in data:
                raise SystemExit("%s uses %s, which the game refuses" % (os.path.basename(path), needle.decode()))
    os.makedirs(os.path.dirname(JAR), exist_ok=True)
    if os.path.exists(JAR):
        os.remove(JAR)
    subprocess.run(["jar", "--create", "--file", JAR, "-C", out, "."], check=True)
    print("jar:", JAR, os.path.getsize(JAR), "bytes")


def stage_and_zip(version):
    if os.path.isdir(STAGE):
        shutil.rmtree(STAGE)
    os.makedirs(STAGE)
    for item in SHIP:
        src = os.path.join(ROOT, item)
        dst = os.path.join(STAGE, item)
        if os.path.isdir(src):
            shutil.copytree(src, dst, ignore=shutil.ignore_patterns("*.bak"))
        else:
            shutil.copy2(src, dst)

    for dp, _, fn in os.walk(STAGE):
        for f in fn:
            if f.endswith((".json", ".csv", ".version")):
                with open(os.path.join(dp, f), "rb") as fh:
                    if fh.read(3) == b"\xef\xbb\xbf":
                        raise SystemExit("BOM in " + f)

    if os.path.exists(ZIP):
        os.remove(ZIP)
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
        for dp, _, fn in os.walk(STAGE):
            for f in fn:
                p = os.path.join(dp, f)
                z.write(p, os.path.relpath(p, ROOT).replace(os.sep, "/"))
    with zipfile.ZipFile(ZIP) as z:
        names = z.namelist()
        for n in names:
            print("  ", n)
        info = json.loads(z.read(STAGE_NAME + "/mod_info.json"))
        if info["version"] != version:
            raise SystemExit("ZIP has the wrong version")
        for need in ("jars/SurvivalModeLite.jar", "data/config/LunaSettings.csv", "data/config/settings.json",
                     "data/config/survival_mode_lite_fields.json", "graphics/icons/survival_mode_lite_icon.png"):
            if STAGE_NAME + "/" + need not in names:
                raise SystemExit("ZIP lacks " + need)
    print("zip:", ZIP, os.path.getsize(ZIP), "bytes, version", version)


if __name__ == "__main__":
    gen_settings_json()
    count, switch_count = gen_luna()
    print(count, "LunaLib value fields,", switch_count, "on/off switches")
    gen_readme()
    gen_forum_post(count, switch_count)
    version = check()
    compile_jar()
    stage_and_zip(version)
